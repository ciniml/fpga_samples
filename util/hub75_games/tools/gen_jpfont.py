#!/usr/bin/env python3
# Makes src/jpfont.rs: 1-bit glyphs of the Japanese text the demos use (and
# printable ASCII), cut from fonts installed on this PC, so the build does
# not need the fonts. Add new text to TEXT and run again:
#   python3 tools/gen_jpfont.py
# S12: IPAGothic 12 px (thin, made for small sizes), B16 / B24: Noto Sans
# CJK JP Bold 16 / 24 px (headings).
from PIL import Image, ImageDraw, ImageFont
import os

TEXT = """
超エレキ万博 ELEKI EXPO 2026 先進テクノロジの祭典 エンジニアを技術で癒す！
ベルサール秋葉原 入場無料 事前登録制 主催 CQ出版社 開幕まで あと 日 時間 分 秒 開催中 本日 閉幕
ご来場ありがとうございました また会いましょう 無線 測位 パワエレ ＡＩ 人工知能
未来エレクトロニクス館 匠の電子工作館 チャレンジ電子工作館 先進テクノロジ館 ジュニア応援館
実習テクノロジ館 体験エレクトロニクス館 7つの館 年月日 月火水木金土日 曜 午前 午後 時計
トランジスタ技術 Interface CQ ham radio 秋葉原 会場 東京都千代田区外神田
ふがふが W40 FPGAを使った デジタルサイネージ用 LEDマトリクスの 点灯制御 ここ 展示 ブース
"""

FONTS = [
    ("S12", "/usr/share/fonts/opentype/ipafont-gothic/ipag.ttf", 12, 0, 110),
    ("B16", "/usr/share/fonts/opentype/noto/NotoSansCJK-Bold.ttc", 16, 0, 110),
    ("B24", "/usr/share/fonts/opentype/noto/NotoSansCJK-Bold.ttc", 24, 0, 110),
]

chars = sorted(set(chr(c) for c in range(32, 127)) | set(TEXT) - set("\n"))
out = [
    "// Generated by tools/gen_jpfont.py (do not edit): 1-bit glyphs, one u32 a row,",
    "// bit (w - 1) is the leftmost pixel. Glyphs are sorted by char.",
    "pub struct Glyph {",
    "    pub ch: char,",
    "    pub adv: u8,",
    "    pub w: u8,",
    "    pub rows: &'static [u32],",
    "}",
    "",
]
for name, path, size, index, thr in FONTS:
    f = ImageFont.truetype(path, size, index=index)
    asc, desc = f.getmetrics()
    h = asc + desc
    # trim the empty rows every glyph shares at the top and bottom
    imgs = {}
    for ch in chars:
        adv = round(f.getlength(ch))
        w = max(adv, 1)
        im = Image.new("L", (w + 4, h), 0)
        ImageDraw.Draw(im).text((0, 0), ch, font=f, fill=255)
        im = im.point(lambda v: 255 if v > thr else 0)
        bbox = im.getbbox()
        if bbox and bbox[2] > w:
            w = min(bbox[2], 32)
        imgs[ch] = (adv, w, im)
    top, bot = h, 0
    for adv, w, im in imgs.values():
        b = im.getbbox()
        if b:
            top, bot = min(top, b[1]), max(bot, b[3])
    out.append(f"pub const {name}_H: i32 = {bot - top};")
    out.append(f"pub const {name}: &[Glyph] = &[")
    for ch in chars:
        adv, w, im = imgs[ch]
        rows = []
        for y in range(top, bot):
            v = 0
            for x in range(w):
                if im.getpixel((x, y)):
                    v |= 1 << (w - 1 - x)
            rows.append(v)
        esc = {"'": "\\'", "\\": "\\\\"}.get(ch, ch)
        out.append(f"    Glyph {{ ch: '{esc}', adv: {adv}, w: {w}, rows: &{rows} }},")
    out.append("];")
    out.append("")

dst = os.path.join(os.path.dirname(__file__), "..", "src", "jpfont.rs")
with open(dst, "w") as fh:
    fh.write("\n".join(out))
print(f"{len(chars)} chars -> {os.path.normpath(dst)}")
