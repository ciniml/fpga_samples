#!/usr/bin/env python3
"""Generates usb3_crc_pkg.veryl: flattened (single-level XOR) parallel CRC updates
for 1..4 data bytes so that synthesis does not build the byte-serial chain.

crc16_wN / crc32_wN advance the reflected CRC registers used in usb3_pkg
(poly 0xD008 / 0xEDB88320, byte 0 of the data word first)."""

def gen(width, poly_refl, nbytes):
    # each register bit is a set (bitmask) of input bits: crc bits 0..width-1, data bits width..width+8*nbytes-1
    state = [1 << i for i in range(width)]
    for b in range(nbytes):
        for i in range(8):
            state[i] ^= 1 << (width + 8 * b + i)
        for _ in range(8):
            fb = state[0]
            new = [state[j + 1] for j in range(width - 1)] + [0]
            for j in range(width):
                if (poly_refl >> j) & 1:
                    new[j] ^= fb
            state = new
    return state

out = ["""// SPDX-License-Identifier: BSL-1.0
// Copyright Kenta Ida 2026.
// Distributed under the Boost Software License, Version 1.0.
//    (See accompanying file LICENSE_1_0.txt or copy at
//          https://www.boost.org/LICENSE_1_0.txt)
/**
 * @file usb3_crc_pkg.veryl
 * @brief Parallel CRC-16 / CRC-32 updates over 1..4 bytes (generated by
 *        gen_crc_pkg.py, do not edit). Same registers and conventions as
 *        the byte-serial helpers in usb3_pkg; flattened so that each
 *        output bit is one XOR of the inputs.
 */
pub package usb3_crc_pkg {"""]
for width, poly, name in ((16, 0xD008, "crc16"), (32, 0xEDB88320, "crc32")):
    for nb in (1, 2, 3, 4):
        st = gen(width, poly, nb)
        out.append(f"    function {name}_w{nb}(crc: input logic<{width}>, d: input logic<{8*nb}>) -> logic<{width}> {{")
        out.append(f"        var r: logic<{width}>;")
        for j in range(width):
            terms = []
            for k in range(width + 8 * nb):
                if (st[j] >> k) & 1:
                    terms.append(f"crc[{k}]" if k < width else f"d[{k - width}]")
            out.append(f"        r[{j}] = {' ^ '.join(terms) if terms else '1\'b0'};")
        out.append("        return r;\n    }")
out.append("}\n")
open("usb3_crc_pkg.veryl", "w").write("\n".join(out))
print("ok")
