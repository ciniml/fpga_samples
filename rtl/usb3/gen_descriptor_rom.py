#!/usr/bin/env python3
"""Generates usb3_descriptor_rom.veryl (word-wide descriptor ROM + usb3_desc_pkg offsets)
for the SuperSpeed device core.

Descriptors (USB 3.2 9.6): device (bcdUSB 3.10, bMaxPacketSize0 = 9 -> 512), one
configuration with one vendor-specific interface and two bulk endpoints (EP1 OUT /
EP1 IN, 1024 bytes) each followed by a SuperSpeed Endpoint Companion (bMaxBurst 0 for
EP1 OUT, IN_MAX_BURST for EP1 IN = Usb3Device IN_BUFS - 1),
strings, the BOS with the USB 2.0 Extension, SuperSpeed USB Device Capability and
Microsoft OS 2.0 platform capability, and the MS OS 2.0 descriptor set (Compatible
ID WINUSB). Each descriptor starts on a 4-byte boundary so that the data packet
framer can read it as words from ROM_BASE + word address.
"""
import sys

MS_VENDOR_CODE = 0x20
ROM_BASE = 0x800   # word address at which the ROM appears on the framer's read port

def le16(x): return [x & 0xff, x >> 8]
def string_desc(s):
    b = s.encode("utf-16-le"); return [2 + len(b), 0x03] + list(b)

dev = ([0x12, 0x01] + le16(0x0310) + [0xFF, 0x00, 0x00, 0x09, "VID_L", "VID_H", "PID_L", "PID_H"]
       + le16(0x0100) + [0x01, 0x02, 0x03, 0x01])
IN_MAX_BURST = 7   # EP1 IN: up to 8 packets per burst (Usb3Device IN_BUFS = 8 packet buffers)
ep_comp = [0x06, 0x30, 0x00, 0x00, 0x00, 0x00]
ep_comp_in = [0x06, 0x30, IN_MAX_BURST, 0x00, 0x00, 0x00]
cfg_body = ([0x09, 0x04, 0x00, 0x00, 0x02, 0xFF, 0x00, 0x00, 0x00] +
            [0x07, 0x05, 0x01, 0x02] + le16(1024) + [0x00] + ep_comp +
            [0x07, 0x05, 0x81, 0x02] + le16(1024) + [0x00] + ep_comp_in)
cfg = [0x09, 0x02] + le16(9 + len(cfg_body)) + [0x01, 0x01, 0x00, 0x80, 0x0D] + cfg_body  # 104 mA (8 mA units)
str0 = [0x04, 0x03, 0x09, 0x04]
str1 = string_desc("fpga_samples")
str2 = string_desc("USB SS Sample")
str3 = string_desc("000001")
msos = ([0x0A, 0x00, 0x00, 0x00, 0x00, 0x00, 0x03, 0x06] + le16(10 + 20) +
        [0x14, 0x00, 0x03, 0x00] + list(b"WINUSB\0\0") + [0] * 8)
uuid = [0xDF, 0x60, 0xDD, 0xD8, 0x89, 0x45, 0xC7, 0x4C, 0x9C, 0xD2, 0x65, 0x9D, 0x9E, 0x64, 0x8A, 0x9F]
cap_usb2 = [0x07, 0x10, 0x02, 0x02, 0x00, 0x00, 0x00]                         # LPM supported
cap_ss = [0x0A, 0x10, 0x03, 0x00] + le16(0x000E) + [0x03, 0x0A] + le16(0x07FF)  # FS/HS/SS, SS full function, U1 10us, U2 2047us
cap_msos = [0x1C, 0x10, 0x05, 0x00] + uuid + [0x00, 0x00, 0x03, 0x06] + le16(len(msos)) + [MS_VENDOR_CODE, 0x00]
bos = [0x05, 0x0F] + le16(5 + len(cap_usb2) + len(cap_ss) + len(cap_msos)) + [0x03] + cap_usb2 + cap_ss + cap_msos

table = [("DEV", dev), ("CFG", cfg), ("STR0", str0), ("STR1", str1), ("STR2", str2), ("STR3", str3),
         ("BOS", bos), ("MSOS", msos)]

out = []
out.append("""// SPDX-License-Identifier: BSL-1.0
// Copyright Kenta Ida 2026.
// Distributed under the Boost Software License, Version 1.0.
//    (See accompanying file LICENSE_1_0.txt or copy at
//          https://www.boost.org/LICENSE_1_0.txt)
/**
 * @file usb3_descriptor_rom.veryl
 * @brief Word-wide descriptor ROM for the SuperSpeed sample device
 *        (generated by gen_descriptor_rom.py, do not edit by hand).
 *
 * Word address (relative to ROM_BASE) and byte length of each descriptor:""")
words = []   # list of 4-element byte lists (symbolic entries allowed)
offs = {}
for name, d in table:
    waddr = len(words)
    offs[name] = (waddr, len(d))
    out.append(f" *   {name:5s} @w{waddr:3d} len {len(d)}")
    padded = d + [0] * ((-len(d)) % 4)
    for i in range(0, len(padded), 4):
        words.append(padded[i:i + 4])
out.append(f""" *
 * bcdUSB 3.10, vendor-specific class, bMaxPacketSize0 = 9 (512 bytes), one
 * configuration with EP1 OUT / EP1 IN bulk (1024 bytes, bMaxBurst 0). The
 * BOS carries the USB 2.0 Extension (LPM), the SuperSpeed USB Device
 * Capability and the Microsoft OS 2.0 platform capability (vendor code
 * 0x{MS_VENDOR_CODE:02X}, descriptor set with Compatible ID WINUSB served at wIndex 7).
 */
pub package usb3_desc_pkg {{
    const ROM_BASE: logic<12> = 12'h{ROM_BASE:03X}; // framer read address of ROM word 0""")
for name, (a, n) in offs.items():
    out.append(f"    const {name}_ADDR: logic<12> = 12'h{ROM_BASE + a:03X};")
    out.append(f"    const {name}_LEN : logic<11> = 11'd{n};")
out.append(f"    const MS_VENDOR_CODE: logic<8> = 8'h{MS_VENDOR_CODE:02X};")
out.append("""}

pub module Usb3DescriptorRom #(
    param VENDOR_ID : logic<16> = 16'h1209,
    param PRODUCT_ID: logic<16> = 16'h0001,
) (
    i_addr: input  logic<8>,  // word address relative to ROM_BASE
    o_data: output logic<32>, // byte 0 of the word in [7:0]
) {
    always_comb {
        case i_addr {""")
sym = {"VID_L": "VENDOR_ID[7:0]", "VID_H": "VENDOR_ID[15:8]", "PID_L": "PRODUCT_ID[7:0]", "PID_H": "PRODUCT_ID[15:8]"}
for i, w in enumerate(words):
    parts = [sym[b] if isinstance(b, str) else f"8'h{b:02X}" for b in reversed(w)]
    out.append(f"            8'd{i}: o_data = {{{', '.join(parts)}}};")
out.append("""            default: o_data = 32'h0;
        }
    }
}
""")
open(sys.argv[1] if len(sys.argv) > 1 else "usb3_descriptor_rom.veryl", "w").write("\n".join(out))
print(f"{len(words)} words: " + ", ".join(f"{k}@w{a}+{n}" for k, (a, n) in offs.items()))
