"""Writes isp_gamma.veryl: 10-bit linear -> 8-bit sRGB transfer ROM.

    python3 tools/gen_gamma.py > isp_gamma.veryl
"""
import sys


def srgb(v):
    return 12.92 * v if v <= 0.0031308 else 1.055 * v ** (1 / 2.4) - 0.055


def main():
    out = sys.stdout
    out.write('''// SPDX-License-Identifier: BSL-1.0
// Copyright Kenta Ida 2026.
// Distributed under the Boost Software License, Version 1.0.
//    (See accompanying file LICENSE_1_0.txt or copy at
//          https://www.boost.org/LICENSE_1_0.txt)
// Generated by tools/gen_gamma.py: do not edit.
/**
 * @file isp_gamma.veryl
 * @brief 10-bit linear -> 8-bit sRGB transfer curve (ROM, one clock).
 */
pub module IspGamma (
    i_clk: input clock,
    i_a  : input logic<10>,
    o_q  : output logic<8>,
) {
    always_ff (i_clk) {
        case i_a {
''')
    for i in range(1024):
        q = min(255, max(0, round(255 * srgb(i / 1023))))
        out.write(f"            10'd{i}: o_q = 8'd{q};\n")
    out.write('''            default: o_q = 8'd0;
        }
    }
}
''')


if __name__ == '__main__':
    main()
