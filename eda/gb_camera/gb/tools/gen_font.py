"""Writes src/font.c: 2 bpp tiles of the characters 0x20-0x5F (colour 3 on 0) from a BDF font
(the X11 misc-fixed 5x8, public domain).

    python3 tools/gen_font.py 5x8.bdf > src/font.c
"""
import sys

glyphs = {}
code, bitmap, rows, bbx = None, False, [], None
for line in open(sys.argv[1]):
    w = line.split()
    if not w:
        continue
    if w[0] == 'ENCODING':
        code = int(w[1])
    elif w[0] == 'BBX':
        bbx = [int(v) for v in w[1:5]]
    elif w[0] == 'BITMAP':
        bitmap, rows = True, []
    elif w[0] == 'ENDCHAR':
        bitmap = False
        if code is not None and 0x20 <= code < 0x60:
            glyphs[code] = (bbx, rows)
    elif bitmap:
        rows.append(int(w[0], 16))

out = sys.stdout
out.write('// SPDX-License-Identifier: BSL-1.0\n// Generated by tools/gen_font.py from the X11 misc-fixed 5x8 font '
          '(public domain): do not edit.\n#include <stdint.h>\n\n'
          'const uint8_t font_tiles[64 * 16] = {\n')
for c in range(0x20, 0x60):
    (w, h, xo, yo), rows = glyphs.get(c, ([5, 8, 0, -1], [0] * 8))
    tile = [0] * 8
    for i, r in enumerate(rows):
        y = 7 - (yo + 1) - (h - 1) + i
        if 0 <= y < 8:
            tile[y] = (r >> 1) & 0x7F        # 5 pixels wide, one column of space on the left
    out.write('    ' + ', '.join(f'0x{b:02X}, 0x{b:02X}' for b in tile) + f',  // {chr(c)!r}\n')
out.write('};\n')
