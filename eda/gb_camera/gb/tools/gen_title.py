"""Writes src/title_data.c: the title picture (drawn here: sky, sun, hills, a camera, the name in the
5x8 font of src/font.c at 2x), as the camera's colour mode would leave it (gb_color_ref.py).

    python3 tools/gen_title.py src/title_data.c [preview.png]
"""
import importlib.util
import os
import re
import sys
from PIL import Image, ImageDraw

here = os.path.dirname(os.path.abspath(__file__))
spec = importlib.util.spec_from_file_location('gb_color_ref', os.path.join(here, '../../../../rtl/chromatic/test/gb_color_ref.py'))
ref = importlib.util.module_from_spec(spec)
spec.loader.exec_module(ref)

W, H = 128, 112
img = Image.new('RGB', (W, H))
d = ImageDraw.Draw(img)
for y in range(H):                                   # sky: deep blue to warm
    t = y / (H - 1)
    d.line([(0, y), (W, y)], fill=(int(30 + 200 * t), int(90 + 110 * t), int(200 - 80 * t)))
d.ellipse([92, 8, 116, 32], fill=(255, 220, 90))     # sun
d.polygon([(0, 84), (30, 62), (58, 80), (86, 58), (128, 82), (128, 112), (0, 112)], fill=(40, 110, 60))
d.polygon([(0, 96), (40, 84), (80, 94), (128, 86), (128, 112), (0, 112)], fill=(30, 80, 40))
# the camera
d.rounded_rectangle([34, 30, 94, 70], radius=6, fill=(50, 50, 60), outline=(20, 20, 24))
d.rectangle([40, 24, 56, 30], fill=(60, 60, 70))
d.ellipse([50, 36, 78, 64], fill=(20, 20, 24))
d.ellipse([54, 40, 74, 60], fill=(60, 120, 200))
d.ellipse([58, 44, 64, 50], fill=(220, 240, 255))
d.rectangle([82, 36, 90, 42], fill=(250, 240, 200))
d.ellipse([86, 26, 92, 30], fill=(220, 40, 40))

# the name in the 5x8 font at 2x, with a shadow
src = open(os.path.join(here, '../src/font.c')).read()
vals = [int(v, 16) for v in re.findall(r'0x([0-9A-F]{2})', src)]


def text(x0, y0, s, col):
    for n, ch in enumerate(s):
        g = vals[(ord(ch) - 32) * 16:(ord(ch) - 32) * 16 + 16:2]
        for yy, row in enumerate(g):
            for xx in range(8):
                if row & (0x80 >> xx):
                    d.rectangle([x0 + n * 12 + xx * 2, y0 + yy * 2, x0 + n * 12 + xx * 2 + 1, y0 + yy * 2 + 1], fill=col)


name = 'GB CAMERA'
x0 = (W - len(name) * 12) // 2
text(x0 + 1, 77, name, (10, 20, 30))
text(x0, 76, name, (255, 255, 240))

fb = [(r >> 3) << 11 | (g >> 2) << 5 | (b >> 3) for r, g, b in img.getdata()]
ram = ref.quant(fb)
with open(sys.argv[1], 'w') as f:
    f.write('// SPDX-License-Identifier: BSL-1.0\n// Generated by tools/gen_title.py: do not edit.\n#include <stdint.h>\n')
    for nm, lo, n in (('title_tiles', 0x100, 0xE00), ('title_attr', 0xF00, 224), ('title_pal', 0x1000, 448)):
        f.write(f'const uint8_t {nm}[{n}] = {{\n')
        for i in range(lo, lo + n, 16):
            f.write('    ' + ', '.join(f'0x{b:02X}' for b in ram[i:i + 16]) + ',\n')
        f.write('};\n')
if len(sys.argv) > 2:
    pair = Image.new('RGB', (W * 2 + 4, H), (255, 0, 0))
    pair.paste(img, (0, 0))
    pair.paste(ref.render(ram), (W + 4, 0))
    pair.resize((pair.width * 3, pair.height * 3), Image.NEAREST).save(sys.argv[2])
