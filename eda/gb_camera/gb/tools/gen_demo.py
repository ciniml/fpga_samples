"""Writes a C file with a colour picture as the camera would leave it (tiles, attributes, palettes;
rtl/chromatic/test/gb_color_ref.py), for `make demo`.

    python3 tools/gen_demo.py out.c [IMAGE]     # no IMAGE: gb_color_ref.py's first synthetic frame
"""
import importlib.util
import os
import sys

here = os.path.dirname(os.path.abspath(__file__))
spec = importlib.util.spec_from_file_location('gb_color_ref', os.path.join(here, '../../../../rtl/chromatic/test/gb_color_ref.py'))
ref = importlib.util.module_from_spec(spec)
spec.loader.exec_module(ref)

fb = ref.load(sys.argv[2])[1] if len(sys.argv) > 2 else ref.synthetic()[0]
ram = ref.quant(fb)
with open(sys.argv[1], 'w') as f:
    f.write('// generated by tools/gen_demo.py\n#include <stdint.h>\n')
    for name, lo, n in (('demo_tiles', 0x100, 0xE00), ('demo_attr', 0xF00, 224), ('demo_pal', 0x1000, 448)):
        f.write(f'const uint8_t {name}[{n}] = {{')
        f.write(','.join(f'0x{b:02X}' for b in ram[lo:lo + n]))
        f.write('};\n')
